test('explicit swipe release leaves ordinary editing untouched', async ({ page }) => {
  await enter(page)
  await page.getByRole('textbox').fill('An intentional gesture.')
  await expect(page.locator('.swipe-surface')).toHaveCount(0)
  await page.getByRole('button', { name: 'Or release with a swipe' }).click()
  const surface = page.locator('.swipe-surface')
  const box = (await surface.boundingBox())!
  await page.mouse.move(box.x + 25, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + Math.min(250, box.width - 10), box.y + box.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect(page.getByRole('button', { name: 'Begin again' })).toBeVisible()
})
