for (const width of [320, 375, 390, 768, 1024, 1440, 1920]) {
  test(`responsive at ${width}px without horizontal overflow or clipped controls`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await enter(page)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('textbox').fill('A thought with room to breathe.')
    const button = page.getByRole('button', { name: 'Let it go', exact: true })
    const box = await button.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(width)
    expect(box!.height).toBeGreaterThanOrEqual(44)
    await expect(button).toBeEnabled()
  })
}

test('full journey arrives without skipping and native undo works', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Enter your space' }).click()
  await expect(page.getByRole('textbox')).toBeVisible({ timeout: 13000 })
  await expect(page.locator('.journey')).toHaveCount(0)
  const editor = page.getByRole('textbox')
  await editor.fill('A thought')
  await editor.press('End')
  await editor.pressSequentially(' to release')
  await expect(editor).toHaveValue('A thought to release')
  await editor.press('ControlOrMeta+z')
  // Browsers group native undo transactions differently; undo must change it and redo restore it.
  await expect(editor).not.toHaveValue('A thought to release')
  await editor.press('ControlOrMeta+Shift+z')
  await expect(editor).toHaveValue('A thought to release')
})

test('long wrapped Unicode text rasterizes in the visible scrolled editor region', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Enter your space' }).click()
  await page.getByRole('button', { name: 'Skip journey' }).click()
  const text = 'A thought that wraps across the paper. '.repeat(240) + '\n\n世界と心 · مرحبا · café 🌙 '.repeat(40)
  const editor = page.locator('textarea')
  await editor.fill(text)
  await editor.evaluate((el: HTMLTextAreaElement) => { el.scrollTop = el.scrollHeight - el.clientHeight - 17; el.dispatchEvent(new Event('scroll', { bubbles: true })) })
  expect(await page.locator('.writing-area').evaluate(el => el.getAttribute('style'))).toContain('--paper-scroll')
  await page.getByRole('button', { name: 'Let it go', exact: true }).click()
  await page.getByRole('button', { name: 'Yes, let it go' }).click()
  await expect(editor).toHaveClass(/ink-transferred/)
  await expect(editor).toHaveValue(text)
  await expect(page.getByRole('button', { name: 'Begin again' })).toBeVisible()
  await page.getByRole('button', { name: /Bring it back/ }).click()
  await expect(editor).toHaveValue(text)
})
